# Homebrew formula template.
#
# `0.1.0` and the `@SHA256_*@` placeholders are substituted by
# .github/workflows/homebrew.yaml from the published release assets, and the
# result is pushed to noirbizarre/homebrew-tap as Formula/over.rb.
class Over < Formula
  desc "A git-based file overlay manager (dotfiles as overlays)"
  homepage "https://noirbizarre.github.io/over/"
  version "0.1.0"
  license "MIT"

  # Prebuilt binaries from the GitHub release rather than a source build:
  # installing takes no Rust toolchain, and libgit2/OpenSSL are already
  # vendored into each binary so there is nothing to link against.
  on_macos do
    on_arm do
      url "https://github.com/noirbizarre/over/releases/download/#{version}/over_#{version}_darwin-arm64.tar.gz"
      sha256 "397b2b79da5fd88fdfefd82f5b8672f34be479b532a2567d5b04c1588eda461e"
    end
    on_intel do
      url "https://github.com/noirbizarre/over/releases/download/#{version}/over_#{version}_darwin-amd64.tar.gz"
      sha256 "faf6f935f0d3fee9d51fc2f600232fa8725285bf8208f15bbdaa935f0ebaae2d"
    end
  end

  # musl rather than gnu: the binaries are statically linked, so they run on
  # any distribution Homebrew supports regardless of its glibc. There is no
  # aarch64-musl leg in the release matrix, so Linux arm64 is left
  # unsupported rather than served a glibc-pinned binary that would fail at
  # load time.
  on_linux do
    on_intel do
      url "https://github.com/noirbizarre/over/releases/download/#{version}/over_#{version}_linux-amd64-musl.tar.gz"
      sha256 "3f2521b95abe96c164808e8f8fe357968e2e7b90b468ca07c3db210433b6e697"
    end
  end

  # Not a build dependency — a usage one. `over git mount` and friends operate
  # on the host's git repository, and `over git mount` is the workflow the
  # documentation leads with.
  depends_on "git"

  def install
    bin.install "over"

    # Generated by the binary rather than taken from the archive, because
    # that is the form Homebrew audits: it runs `over completion <shell>` for
    # each shell and files the output where that shell looks for it. `shell`
    # is a required positional argument with no flag form, so this relies on
    # Homebrew's default parameter format, which passes it plainly as a
    # trailing argument.
    generate_completions_from_executable(bin/"over", "completion")
  end

  test do
    assert_match version.to_s, shell_output("#{bin}/over --version")
    assert_match "overlay", shell_output("#{bin}/over --help")
  end
end
